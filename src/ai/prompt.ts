function formatRule(length: AnswerLength): string {
  return length === 'short'
    ? 'Длина: коротко — 2–5 предложений или небольшой список. На приветствие и small talk — одна-две фразы.'
    : 'Длина: подробно, но по делу — до 12–15 предложений, можно со списками.';
}

/** Пример с условными номерами: модели копируют формат, а не конкретный пункт. */
const EXAMPLE_Q = 'можна ли провоцироват гос сотрудника?';
const EXAMPLE_A =
  '**Нет**, за это наказывают: пункт N.N запрещает намеренно провоцировать сотрудников госструктур на погони и задержания [1]. ' +
  'Наказание — то, что указано в этом пункте [1].';

/** OpenAI, xAI и прочие универсальные модели: нумерованные правила. */
function standard(length: AnswerLength, question: string, fragments: ContextFragment[]): BuiltPrompt {
  const system = [
    ROLE,
    'Правила:',
    ...CORE.map((r, i) => `${i + 1}. ${r}`),
    formatRule(length),
    `Пример формата (номер пункта и наказание всегда бери из контекста): «${EXAMPLE_Q}» → «${EXAMPLE_A}»`,
  ].join('\n');
  const ctx = fragments.length
    ? fragments.map((f) => `[${f.n}] ${label(f)}\n${f.text}`).join('\n\n---\n\n')
    : NO_CONTEXT;
  return { system, user: `КОНТЕКСТ:\n${ctx}\n\nСООБЩЕНИЕ ИГРОКА:\n${question}`, temperature: 0.4 };
}

/** Claude: лучше всего понимает структуру на XML-тегах и разделение данных и инструкций. */
function claude(length: AnswerLength, question: string, fragments: ContextFragment[]): BuiltPrompt {
  const system = [
    ROLE,
    'Материалы форума по теме вопроса будут в теге <context>, сообщение игрока — в <question>.',
    '',
    '<rules>',
    ...CORE.map((r) => `- ${r}`),
    `- ${formatRule(length)}`,
    '</rules>',
    '',
    '<example>',
    `Вопрос: ${EXAMPLE_Q}`,
    `Ответ: ${EXAMPLE_A}`,
    '(N.N и наказание в реальном ответе — из <context>.)',
    '</example>',
  ].join('\n');
  const ctx = fragments.length
    ? fragments.map((f) => `<fragment n="${f.n}" title="${label(f).replace(/["<>]/g, "'")}">\n${f.text}\n</fragment>`).join('\n')
    : NO_CONTEXT;
  return { system, user: `<context>\n${ctx}\n</context>\n\n<question>\n${question}\n</question>`, temperature: 0.4 };
}

/** Gemini: склонен к длинным ответам и Markdown-заголовкам — явно ограничиваем стиль. */
function gemini(length: AnswerLength, question: string, fragments: ContextFragment[]): BuiltPrompt {
  const base = standard(length, question, fragments);
  const system = [
    base.system,
    'Дополнительно:',
    '- Не используй заголовки (#).',
    '- Не повторяй вопрос и не пересказывай весь контекст — только то, что отвечает на вопрос.',
    length === 'short' ? '- Ответ должен помещаться в один короткий абзац или список до 5 пунктов.' : '',
  ]
    .filter(Boolean)
    .join('\n');
  return { system, user: base.user, temperature: 0.4 };
}

