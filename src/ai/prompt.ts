import type { PromptStyle } from './providers.js';

export type AnswerLength = 'short' | 'long';

export interface ContextFragment {
  n: number;
  title: string;
  url: string;
  text: string;
  /** rule — пункт правил, complaint — разбор конкретной жалобы, forum — прочая тема форума. */
  kind?: 'rule' | 'complaint' | 'forum';
}

const KIND_LABEL: Record<NonNullable<ContextFragment['kind']>, string> = {
  rule: 'правила',
  complaint: 'жалоба — разбор конкретного случая',
  forum: 'тема форума',
};

function label(f: ContextFragment): string {
  return f.kind ? `${KIND_LABEL[f.kind]}: ${f.title}` : f.title;
}

export interface BuiltPrompt {
  system: string;
  user: string;
  temperature: number;
}

