export function buildPrompt(
  style: PromptStyle,
  length: AnswerLength,
  question: string,
  fragments: ContextFragment[],
  serverInstructions?: string | null,
): BuiltPrompt {
  const p =
    style === 'claude'
      ? claude(length, question, fragments)
      : style === 'gemini'
        ? gemini(length, question, fragments)
        : style === 'compact'
          ? compact(length, question, fragments)
          : standard(length, question, fragments);
  if (serverInstructions) {
    // Указания администрации сервера дополняют, но не отменяют основные правила (язык, факты из контекста, приватность).
    const block =
      style === 'claude'
        ? `<server_instructions>\n${serverInstructions}\n</server_instructions>\nСоблюдай эти указания, если они не противоречат <rules>.`
        : `Дополнительные указания администрации сервера (соблюдай, если они не противоречат правилам выше):\n${serverInstructions}`;
    p.system = `${p.system}\n\n${block}`;
  }
  return p;
}

/** Номера фрагментов, на которые сослался ответ модели. */
export function citedNumbers(answer: string): number[] {
  const nums = new Set<number>();
  for (const m of answer.matchAll(/\[(\d{1,2})\]/g)) nums.add(Number(m[1]));
  return [...nums].sort((a, b) => a - b);
}
