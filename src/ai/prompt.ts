function formatRule(length: AnswerLength): string {
  return length === 'short'
    ? 'Длина: коротко — 2–5 предложений или небольшой список. На приветствие и small talk — одна-две фразы.'
    : 'Длина: подробно, но по делу — до 12–15 предложений, можно со списками.';
}

/** Пример с условными номерами: модели копируют формат, а не конкретный пункт. */
const EXAMPLE_Q = 'можна ли провоцироват гос сотрудника?';
const EXAMPLE_A =
  '**Нет**, за это наказывают: пункт N.N запрещает намеренно провоцировать сотрудников госструктур на погони и задержания [1]. ' +
  'Наказание — то, что указано в этом пункте [1].';

/** OpenAI, xAI и прочие универсальные модели: нумерованные правила. */
function standard(length: AnswerLength, question: string, fragments: ContextFragment[], forumOnly: boolean): BuiltPrompt {
  const system = [
    role(forumOnly),
    'Правила:',
    ...core(forumOnly).map((r, i) => `${i + 1}. ${r}`),
    formatRule(length),
    `Пример формата (номер пункта и наказание всегда бери из контекста): «${EXAMPLE_Q}» → «${EXAMPLE_A}»`,
  ].join('\n');
  const ctx = fragments.length
    ? fragments.map((f) => `[${f.n}] ${label(f)}\n${f.text}`).join('\n\n---\n\n')
    : NO_CONTEXT;
  return { system, user: `КОНТЕКСТ:\n${ctx}\n\nСООБЩЕНИЕ ИГРОКА:\n${question}`, temperature: 0.4 };
}

/** Claude: лучше всего понимает структуру на XML-тегах и разделение данных и инструкций. */
function claude(length: AnswerLength, question: string, fragments: ContextFragment[], forumOnly: boolean): BuiltPrompt {
  const system = [
    role(forumOnly),
    'Материалы форума по теме вопроса будут в теге <context>, сообщение игрока — в <question>.',
    '',
    '<rules>',
    ...core(forumOnly).map((r) => `- ${r}`),
    `- ${formatRule(length)}`,
    '- Без заголовков (#) и без пересказа вопроса или всего контекста — только то, что отвечает на вопрос.',
    '- Фрагменты не по теме молча пропускай: не перечисляй, что нашлось или не нашлось в контексте, и не пересказывай чужие правила (допросы, правила лидеров и т. п.), если вопрос не о них.',
    '- Если ответ уже дан (из пункта или из общих знаний), не добавляй «точного определения нет», «уточните у администрации».',
    '</rules>',
    '',
    '<example>',
    `Вопрос: ${EXAMPLE_Q}`,
    `Ответ: ${EXAMPLE_A}`,
    '(N.N и наказание в реальном ответе — из <context>.)',
    '</example>',
  ].join('\n');
  const ctx = fragments.length
    ? fragments.map((f) => `<fragment n="${f.n}" title="${label(f).replace(/["<>]/g, "'")}">\n${f.text}\n</fragment>`).join('\n')
    : NO_CONTEXT;
  // Haiku без напоминания в конце пишет длиннее заданного, а решения по правилам («вопрос про ивент, значит…»)
  // проговаривает прямо в ответе. Поэтому — черновик в <analysis>: бот его вырезает (stripReasoning), игрок видит только <answer>.
  const reminder =
    'Сначала в <analysis> коротко для себя: о чём на самом деле вопрос; какие [n] отвечают на него прямо (только их и бери); ' +
    'вопрос «можно ли / накажут ли / запрещено ли» или нет; вопрос про конкретное мероприятие/место или общий. ' +
    'Затем в <answer> — только ответ игроку по схеме: сразу суть → пункт и наказание [n] → конец' +
    (length === 'short' ? ', не больше 4 предложений' : '') + '. ' +
    'На «можно ли» первое слово — **Да** (можно), **Нет** (нельзя) или **Зависит от ситуации**; на остальные — без них. ' +
    'Вопрос про мероприятие или место — ответ из его правил; вопрос общий, а нашлись только правила отдельного места или ивента — начни с «Общего правила об этом не нашёл». ' +
    'Ничего подходящего — одна фраза: «На форуме NOVA RP об этом не нашёл». ' +
    'В <answer> не пересказывай вопрос и свои рассуждения, не упоминай контекст и поиск, не пиши, чего в правилах нет, и не советуй уточнить у администрации, если ответ уже дан.';
  return { system, user: `<context>\n${ctx}\n</context>\n\n<question>\n${question}\n</question>\n\n${reminder}`, temperature: 0.2 };
}

/** Gemini: склонен к длинным ответам и Markdown-заголовкам — явно ограничиваем стиль. */
function gemini(length: AnswerLength, question: string, fragments: ContextFragment[], forumOnly: boolean): BuiltPrompt {
  const base = standard(length, question, fragments, forumOnly);
  const system = [
    base.system,
    'Дополнительно:',
    '- Не используй заголовки (#).',
    '- Не повторяй вопрос и не пересказывай весь контекст — только то, что отвечает на вопрос.',
    length === 'short' ? '- Ответ должен помещаться в один короткий абзац или список до 5 пунктов.' : '',
  ]
    .filter(Boolean)
    .join('\n');
  // Лёгкие модели Gemini (flash-lite) лучше слушаются напоминания в конце, чем правил в середине системного промпта.
  const user =
    `${base.user}\n\n` +
    'Перед ответом проверь каждый фрагмент: он отвечает ИМЕННО на этот вопрос? Бери такие. ' +
    'Есть близкий пункт, который отвечает лишь частично, — назови его и прямо скажи, чего в нём нет (например: «прямо про OOC не нашёл, но пункт 4.13 запрещает мат в отыгровках»). ' +
    'Игрок жалуется на ситуацию (кикнули, забанили, наказали, обманули) — подскажи процедуру из фрагментов: жалоба на администратора или игрока, обжалование. ' +
    'Совсем ничего подходящего нет — честно скажи, что на форуме не нашёл (без **Да**/**Нет** в начале), без догадок и выдуманных «в целом запрещено». ' +
    (forumOnly
      ? 'Из общих знаний ничего не добавляй: только то, что есть во фрагментах, со ссылками [n].'
      : 'На болтовню, шутки и благодарности отвечай без фрагментов и без [n].');
  return { system, user, temperature: 0.4 };
}

